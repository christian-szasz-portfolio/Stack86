// Hello Arithmetic — basic cout and operators
#include <iostream>
using namespace std;

int main() {
    int a = 15;
    int b = 7;

    cout << "Sum: " << a + b << endl;
    cout << "Diff: " << a - b << endl;
    cout << "Prod: " << a * b << endl;
    cout << "Quot: " << a / b << endl;
    cout << "Rem: " << a % b << endl;

    return 0;
}
