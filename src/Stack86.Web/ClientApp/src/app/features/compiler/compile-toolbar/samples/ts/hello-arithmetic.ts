// Hello Arithmetic — typed variables and math
const a: number = 10;
const b: number = 3;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);

const neg: number = -a;
console.log(neg);

// Compound assignment
let aVar: number = a;
let bVar: number = b;
aVar += 5;
bVar *= 2;
console.log(aVar);
console.log(bVar);
