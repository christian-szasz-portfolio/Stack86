// Hello Arithmetic — basic Console output and operators
using System;

class Program
{
    static int Main()
    {
        int a = 15;
        int b = 7;

        Console.WriteLine("Sum: " + (a + b));
        Console.WriteLine("Diff: " + (a - b));
        Console.WriteLine("Prod: " + (a * b));
        Console.WriteLine("Quot: " + (a / b));
        Console.WriteLine("Rem: " + (a % b));

        return 0;
    }
}
